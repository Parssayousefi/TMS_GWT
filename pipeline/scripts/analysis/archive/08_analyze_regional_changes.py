#!/usr/bin/env python3
"""
Detailed Regional Analysis of Drug Effects
===========================================

This script identifies which specific regions show ΦR changes in drug vs control:
1. Load significant edge masks from NBS
2. Calculate node degree (how many significant edges each region has)
3. Identify most affected regions
4. Compare with gateway/broadcaster classification
5. Analyze RSN-specific patterns

**UPDATED**: Now dataset-aware - works with any drug/control comparison

This addresses the question: "Which regions exactly showed reduction vs increases?"
"""

import numpy as np
import pandas as pd
from pathlib import Path
import yaml
import sys
import argparse

# Add utils directory to path for loading ROI mapping
sys.path.insert(0, str(Path(__file__).parent.parent / 'utils'))
from load_roi_mapping import load_roi_network_mapping
from dataset_handler import load_dataset_handler
from analysis_loader import get_control_task_name

# Parameters
N_ROIS = 454

def get_rsn_labels_and_names(base_dir):
    """
    Get RSN labels and names from CSV mapping file

    Loads from CSV file generated by create_roi_network_mapping.py
    This CSV contains both Schaefer 400 and Tian 54 mappings with proper labels.

    Returns
    -------
    rsn_labels : array (454,)
        Network ID for each ROI (0-7)
    rsn_names_per_roi : array (454,)
        Network name for each ROI
    rsn_name_list : list
        List of unique RSN names
    """
    print("  Loading ROI to network mapping from CSV...")
    rsn_labels, rsn_name_list, roi_df = load_roi_network_mapping(base_dir)

    # Get network name for each ROI (not just unique names)
    # roi_df includes background at index 0, so we need to filter
    rsn_names_per_roi = roi_df[roi_df['ROI'] > 0]['Network_Name'].values

    # Verify we have all 454 ROIs
    if len(rsn_labels) != N_ROIS:
        raise ValueError(f"Expected {N_ROIS} ROIs, got {len(rsn_labels)}")

    print(f"  ✓ Loaded RSN labels for {N_ROIS} ROIs")

    # Print network distribution
    print("  RSN distribution:")
    for i, name in enumerate(rsn_name_list):
        count = np.sum(rsn_labels == i)
        print(f"    {name}: {count} ROIs")

    return rsn_labels, rsn_names_per_roi, rsn_name_list

def load_nbs_results(nbs_dir, prefix):
    """Load NBS results"""
    sig_increases = np.load(nbs_dir / f'{prefix}_sig_increases_mask.npy')
    sig_decreases = np.load(nbs_dir / f'{prefix}_sig_decreases_mask.npy')

    with open(nbs_dir / f'{prefix}_nbs_metadata.yaml', 'r') as f:
        metadata = yaml.safe_load(f)

    return sig_increases, sig_decreases, metadata

def load_workspace_info(workspace_dir, prefix):
    """Load gateway/broadcaster classifications"""
    workspace_df = pd.read_csv(workspace_dir / f'{prefix}_workspace_summary.csv')
    gateway_df = pd.read_csv(workspace_dir / f'{prefix}_gateway_broadcaster_summary.csv')

    return workspace_df, gateway_df

def calculate_node_involvement(edge_mask):
    """
    Calculate how many significant edges each node has

    Parameters
    ----------
    edge_mask : array (454, 454)
        Binary mask of significant edges

    Returns
    -------
    node_degree : array (454,)
        Number of significant edges for each node
    """
    # Since it's symmetric, just sum along one axis and multiply by 2
    # But diagonal is 0, so this works
    node_degree = edge_mask.sum(axis=0) + edge_mask.sum(axis=1)
    return node_degree

def main():
    """Main analysis"""
    parser = argparse.ArgumentParser(
        description='Regional analysis of drug effects - DATASET AWARE'
    )
    parser.add_argument('--dataset', required=True,
                       help='Dataset name (e.g., london_lsd, basel_mmm)')
    parser.add_argument('--drug_task', required=True,
                       help='Drug/experimental task name (e.g., LSD, MDMA)')
    parser.add_argument('--project_dir', help='Project directory (optional)')
    parser.add_argument('--workspace_dataset', default='hcp',
                       help='Dataset that defines the canonical workspace (default: hcp). '
                       'The HCP workspace is the canonical reference per Luppi et al.')

    args = parser.parse_args()

    # Load dataset handler
    handler = load_dataset_handler(args.dataset, project_dir=args.project_dir)

    # Get control task
    control_task = get_control_task_name(args.dataset)

    # Setup paths
    base_results_dir = handler.project_dir / 'results' / 'group_analysis'

    # Workspace source: use workspace_dataset if specified
    ws_ds = args.workspace_dataset if args.workspace_dataset else args.dataset
    ws_ctrl = get_control_task_name(ws_ds) if ws_ds != args.dataset else control_task
    workspace_dir = base_results_dir / ws_ds / ws_ctrl
    workspace_prefix = f"{ws_ds}_{ws_ctrl}"

    nbs_dir = base_results_dir / args.dataset / f'nbs_{args.drug_task}_vs_{control_task}'
    output_dir = base_results_dir / args.dataset / f'regional_effects_{args.drug_task}_vs_{control_task}'
    output_dir.mkdir(exist_ok=True, parents=True)

    # File prefixes
    nbs_prefix = f"{args.dataset}_{args.drug_task}_vs_{control_task}"
    output_prefix = f"{args.dataset}_{args.drug_task}_vs_{control_task}"

    # Create markdown output list
    md_output = []

    def print_and_log(msg):
        """Print to console and log to markdown"""
        print(msg)
        md_output.append(msg)

    print_and_log("="*70)
    print_and_log(f"REGIONAL ANALYSIS: {args.drug_task} EFFECTS ON ΦR")
    print_and_log("="*70)
    print_and_log(f"\nDataset: {handler.config['name']}")
    print_and_log(f"Comparison: {args.drug_task} vs {control_task}")
    print_and_log(f"Workspace source: {ws_ds}/{ws_ctrl}")
    print_and_log("")

    # Load data
    print_and_log("Loading data...")

    # Load RSN labels
    rsn_labels, rsn_names_per_roi, rsn_name_list = get_rsn_labels_and_names(handler.project_dir)

    # Load NBS results
    try:
        sig_increases, sig_decreases, nbs_metadata = load_nbs_results(nbs_dir, nbs_prefix)
    except FileNotFoundError as e:
        print_and_log(f"\nERROR: Could not find NBS results")
        print_and_log(f"  {e}")
        print_and_log(f"\nPlease run 07_network_based_statistics.py first:")
        print_and_log(f"  python scripts/analysis/07_network_based_statistics.py --dataset {args.dataset} --drug_task {args.drug_task}")
        return

    # Load workspace info
    try:
        workspace_df, gateway_df = load_workspace_info(workspace_dir, workspace_prefix)
    except FileNotFoundError as e:
        print_and_log(f"\nERROR: Could not find workspace results")
        print_and_log(f"  {e}")
        print_and_log(f"\nPlease run these scripts first:")
        print_and_log(f"  1. python scripts/analysis/05_group_average_workspace.py --dataset {args.dataset}")
        print_and_log(f"  2. python scripts/analysis/06_identify_gateways_broadcasters.py --dataset {args.dataset}")
        return

    print_and_log("✓ Data loaded")
    print_and_log("")

    # Calculate node involvement
    print_and_log("Calculating regional involvement...")
    increases_degree = calculate_node_involvement(sig_increases)
    decreases_degree = calculate_node_involvement(sig_decreases)
    print_and_log("✓ Node degrees calculated")
    print_and_log("")

    # Create comprehensive DataFrame
    results_df = pd.DataFrame({
        'ROI': np.arange(N_ROIS),
        'RSN': rsn_names_per_roi,
        'RSN_id': rsn_labels,
        'n_edges_increased': increases_degree.astype(int),
        'n_edges_decreased': decreases_degree.astype(int),
        'net_change': (increases_degree - decreases_degree).astype(int),
        'total_affected_edges': (increases_degree + decreases_degree).astype(int),
        'workspace_member': workspace_df['workspace_member'].values,
        'synergy_strength': workspace_df['synergy_strength'].values,
        'redundancy_strength': workspace_df['redundancy_strength'].values,
        'synergy_rank': workspace_df['synergy_rank'].values,
        'redundancy_rank': workspace_df['redundancy_rank'].values
    })

    # Add gateway/broadcaster info
    # Create classification from gateway and broadcaster boolean columns
    def classify_role(row):
        if row['gateway']:
            return 'Gateway'
        elif row['broadcaster']:
            return 'Broadcaster'
        elif row['workspace']:
            return 'Workspace (unclassified)'
        else:
            return 'Not in workspace'

    gateway_df['classification'] = gateway_df.apply(classify_role, axis=1)

    gateway_info = gateway_df.set_index('ROI')['classification'].to_dict()
    results_df['gateway_broadcaster'] = results_df['ROI'].map(gateway_info)

    # =========================================================================
    # Analysis 1: Most affected regions (by total edges)
    # =========================================================================
    print_and_log("="*70)
    print_and_log(f"TOP 20 REGIONS WITH MOST ΦR CHANGES ({args.drug_task} vs {control_task})")
    print_and_log("="*70)
    print_and_log("")

    top_affected = results_df.nlargest(20, 'total_affected_edges')

    print_and_log(f"{'Rank':<5} {'ROI':<5} {'Network':<15} {'Role':<12} "
          f"{'Increases':<10} {'Decreases':<10} {'Net':<8}")
    print_and_log("-"*70)

    for idx, (rank, row) in enumerate(top_affected.iterrows(), 1):
        print_and_log(f"{rank:<5} {row['ROI']:<5} {row['RSN']:<15} "
              f"{row['gateway_broadcaster']:<12} "
              f"{row['n_edges_increased']:<10} {row['n_edges_decreased']:<10} "
              f"{row['net_change']:<8}")

    print_and_log("")

    # =========================================================================
    # Analysis 2: Most increased regions
    # =========================================================================
    print_and_log("="*70)
    print_and_log(f"TOP 20 REGIONS WITH INCREASED ΦR ({args.drug_task} > {control_task})")
    print_and_log("="*70)
    print_and_log("")

    top_increased = results_df.nlargest(20, 'n_edges_increased')

    print_and_log(f"{'Rank':<5} {'ROI':<5} {'Network':<15} {'Role':<12} {'N Edges':<10}")
    print_and_log("-"*70)

    for idx, (rank, row) in enumerate(top_increased.iterrows(), 1):
        if row['n_edges_increased'] > 0:
            print_and_log(f"{rank:<5} {row['ROI']:<5} {row['RSN']:<15} "
                  f"{row['gateway_broadcaster']:<12} {row['n_edges_increased']:<10}")

    print_and_log("")

    # =========================================================================
    # Analysis 3: Most decreased regions
    # =========================================================================
    print_and_log("="*70)
    print_and_log(f"TOP 20 REGIONS WITH DECREASED ΦR ({args.drug_task} < {control_task})")
    print_and_log("="*70)
    print_and_log("")

    top_decreased = results_df.nlargest(20, 'n_edges_decreased')

    print_and_log(f"{'Rank':<5} {'ROI':<5} {'Network':<15} {'Role':<12} {'N Edges':<10}")
    print_and_log("-"*70)

    for idx, (rank, row) in enumerate(top_decreased.iterrows(), 1):
        if row['n_edges_decreased'] > 0:
            print_and_log(f"{rank:<5} {row['ROI']:<5} {row['RSN']:<15} "
                  f"{row['gateway_broadcaster']:<12} {row['n_edges_decreased']:<10}")

    print_and_log("")

    # =========================================================================
    # Analysis 4: Gateway vs Broadcaster effects
    # =========================================================================
    print_and_log("="*70)
    print_and_log("GATEWAY VS BROADCASTER EFFECTS")
    print_and_log("="*70)
    print_and_log("")

    # Only workspace regions
    workspace_results = results_df[results_df['workspace_member'] == True].copy()

    # Separate gateways and broadcasters
    gateways = workspace_results[workspace_results['gateway_broadcaster'] == 'Gateway']
    broadcasters = workspace_results[workspace_results['gateway_broadcaster'] == 'Broadcaster']

    print_and_log(f"Gateways (n={len(gateways)}):")
    print_and_log(f"  Edges increased: {gateways['n_edges_increased'].sum()} (mean: {gateways['n_edges_increased'].mean():.1f} per region)")
    print_and_log(f"  Edges decreased: {gateways['n_edges_decreased'].sum()} (mean: {gateways['n_edges_decreased'].mean():.1f} per region)")
    print_and_log(f"  Regions with any decrease: {(gateways['n_edges_decreased'] > 0).sum()}/{len(gateways)}")
    print_and_log("")

    print_and_log(f"Broadcasters (n={len(broadcasters)}):")
    print_and_log(f"  Edges increased: {broadcasters['n_edges_increased'].sum()} (mean: {broadcasters['n_edges_increased'].mean():.1f} per region)")
    print_and_log(f"  Edges decreased: {broadcasters['n_edges_decreased'].sum()} (mean: {broadcasters['n_edges_decreased'].mean():.1f} per region)")
    print_and_log(f"  Regions with any decrease: {(broadcasters['n_edges_decreased'] > 0).sum()}/{len(broadcasters)}")
    print_and_log("")

    # =========================================================================
    # Analysis 5: RSN-level summary
    # =========================================================================
    print_and_log("="*70)
    print_and_log("NETWORK-LEVEL SUMMARY")
    print_and_log("="*70)
    print_and_log("")

    rsn_summary = results_df.groupby('RSN').agg({
        'n_edges_increased': 'sum',
        'n_edges_decreased': 'sum',
        'ROI': 'count'
    }).rename(columns={'ROI': 'n_regions'})

    rsn_summary['mean_increases'] = results_df.groupby('RSN')['n_edges_increased'].mean()
    rsn_summary['mean_decreases'] = results_df.groupby('RSN')['n_edges_decreased'].mean()
    rsn_summary['regions_with_decreases'] = results_df.groupby('RSN').apply(
        lambda x: (x['n_edges_decreased'] > 0).sum()
    )

    print_and_log(f"{'Network':<18} {'N ROIs':<8} {'Total Inc':<10} {'Total Dec':<10} "
          f"{'Mean Inc':<10} {'Mean Dec':<10} {'N Dec>0':<8}")
    print_and_log("-"*80)

    for network in rsn_summary.index:
        row = rsn_summary.loc[network]
        print_and_log(f"{network:<18} {row['n_regions']:<8} "
              f"{row['n_edges_increased']:<10.0f} {row['n_edges_decreased']:<10.0f} "
              f"{row['mean_increases']:<10.1f} {row['mean_decreases']:<10.1f} "
              f"{row['regions_with_decreases']:<8.0f}")

    print_and_log("")

    # =========================================================================
    # Analysis 6: Gateway regions with decreases
    # =========================================================================
    print_and_log("="*70)
    print_and_log("GATEWAY REGIONS WITH ΦR DECREASES")
    print_and_log("="*70)
    print_and_log("")
    print_and_log("Paper prediction: Loss of consciousness affects DMN gateways")
    print_and_log(f"Current analysis: {args.drug_task} is altered (not lost) consciousness")
    print_and_log("")

    gateway_decreases = gateways[gateways['n_edges_decreased'] > 0].sort_values(
        'n_edges_decreased', ascending=False
    )

    if len(gateway_decreases) > 0:
        print_and_log(f"{'ROI':<5} {'Network':<15} {'N Decreased':<12} {'Synergy Rank':<13}")
        print_and_log("-"*50)
        for idx, row in gateway_decreases.iterrows():
            print_and_log(f"{row['ROI']:<5} {row['RSN']:<15} "
                  f"{row['n_edges_decreased']:<12} {row['synergy_rank']:<13.0f}")
    else:
        print_and_log("No gateway regions show significant ΦR decreases")

    print_and_log("")

    # =========================================================================
    # Save results
    # =========================================================================
    print_and_log("="*70)
    print_and_log("SAVING RESULTS")
    print_and_log("="*70)
    print_and_log("")

    # Save full results
    results_df.to_csv(output_dir / f'{output_prefix}_regional_effects.csv', index=False)
    print_and_log(f"✓ Saved: {output_prefix}_regional_effects.csv")

    # Save top affected regions
    top_affected.to_csv(output_dir / f'{output_prefix}_top_affected_regions.csv', index=False)
    print_and_log(f"✓ Saved: {output_prefix}_top_affected_regions.csv")

    # Save RSN summary
    rsn_summary.to_csv(output_dir / f'{output_prefix}_rsn_summary.csv')
    print_and_log(f"✓ Saved: {output_prefix}_rsn_summary.csv")

    # Save workspace-specific results
    workspace_summary = pd.DataFrame({
        'Category': ['Gateways', 'Broadcasters'],
        'N_regions': [len(gateways), len(broadcasters)],
        'Total_edges_increased': [gateways['n_edges_increased'].sum(),
                                   broadcasters['n_edges_increased'].sum()],
        'Total_edges_decreased': [gateways['n_edges_decreased'].sum(),
                                   broadcasters['n_edges_decreased'].sum()],
        'Mean_edges_increased': [gateways['n_edges_increased'].mean(),
                                  broadcasters['n_edges_increased'].mean()],
        'Mean_edges_decreased': [gateways['n_edges_decreased'].mean(),
                                  broadcasters['n_edges_decreased'].mean()],
        'N_regions_with_decreases': [(gateways['n_edges_decreased'] > 0).sum(),
                                      (broadcasters['n_edges_decreased'] > 0).sum()]
    })
    workspace_summary.to_csv(output_dir / f'{output_prefix}_workspace_effects.csv', index=False)
    print_and_log(f"✓ Saved: {output_prefix}_workspace_effects.csv")

    # Save metadata
    metadata = {
        'dataset': args.dataset,
        'dataset_name': handler.config['name'],
        'drug_task': args.drug_task,
        'control_task': control_task,
        'workspace_source_dataset': ws_ds,
        'workspace_source_task': ws_ctrl,
        'workspace_source_path': str(workspace_dir),
        'n_sig_increases': int(nbs_metadata['n_sig_increases']),
        'n_sig_decreases': int(nbs_metadata['n_sig_decreases']),
        'n_regions_with_decreases': int((results_df['n_edges_decreased'] > 0).sum()),
        'n_gateways_affected': int((gateways['n_edges_decreased'] > 0).sum()),
        'n_broadcasters_affected': int((broadcasters['n_edges_decreased'] > 0).sum()),
        'analysis_date': pd.Timestamp.now().isoformat(),
        'output_directory': str(output_dir),
        'file_prefix': output_prefix
    }

    with open(output_dir / f'{output_prefix}_regional_effects_metadata.yaml', 'w') as f:
        yaml.dump(metadata, f, default_flow_style=False)
    print_and_log(f"✓ Saved: {output_prefix}_regional_effects_metadata.yaml")

    print_and_log("")
    print_and_log("="*70)
    print_and_log("ANALYSIS COMPLETE")
    print_and_log("="*70)
    print_and_log("")
    print_and_log(f"Results saved to: {output_dir}")
    print_and_log(f"File prefix: {output_prefix}_*")
    print_and_log("")
    print_and_log("Key findings:")
    print_and_log(f"  - {nbs_metadata['n_sig_decreases']} edges decreased")
    print_and_log(f"  - {nbs_metadata['n_sig_increases']} edges increased")
    print_and_log(f"  - {(results_df['n_edges_decreased'] > 0).sum()} regions show any decrease")
    print_and_log(f"  - {(gateways['n_edges_decreased'] > 0).sum()}/{len(gateways)} gateways affected")
    print_and_log(f"  - {(broadcasters['n_edges_decreased'] > 0).sum()}/{len(broadcasters)} broadcasters affected")
    print_and_log("")
    print_and_log("Next steps:")
    print_and_log("  1. Review top affected regions")
    print_and_log("  2. Check if DMN gateways are predominantly affected")
    print_and_log("  3. Run visualization scripts")
    print_and_log("")

    # Save markdown output
    md_file = output_dir / f'{output_prefix}_regional_effects_report.md'
    with open(md_file, 'w') as f:
        f.write('\n'.join(md_output))
    print(f"\n✓ Markdown report saved to: {md_file}")

if __name__ == '__main__':
    main()
