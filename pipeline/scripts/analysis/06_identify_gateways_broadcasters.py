def compute_participation_coefficient(connectivity_matrix, module_labels):
    """
    Compute participation coefficient for each node

    From Rubinov & Sporns (2010) and Luppi et al. (2024):
    P_i = 1 - sum_s=1^M (κ_is / k_i)^2

    NaN-aware: zero-variance ROI pairs upstream are encoded as NaN.
    - k_i and κ_is use np.nansum (NaN edges do not contribute).
    - ROIs with all-NaN rows (or k_i == 0) return NaN PC rather than 0,
      so they cannot be spuriously classified as gateway or broadcaster.

    Parameters
    ----------
    connectivity_matrix : array (N, N)
        Connectivity matrix (synergy or redundancy); NaN = missing edge
    module_labels : array (N,)
        Module assignment for each node

    Returns
    -------
    participation_coef : array (N,)
        Participation coefficient for each node (NaN where ROI has no valid edges)
    """
    N = connectivity_matrix.shape[0]
    modules = np.unique(module_labels)

    # Total strength for each node, ignoring NaN edges
    k_i = np.nansum(connectivity_matrix, axis=1)
    all_nan_row = np.all(np.isnan(connectivity_matrix), axis=1)

    # Participation coefficient
    participation_coef = np.zeros(N)

    for i in range(N):
        # ROI with no valid edges or zero strength → NaN (not 0) so it cannot
        # be ranked spuriously against real ROIs downstream
        if all_nan_row[i] or k_i[i] == 0:
            participation_coef[i] = np.nan
            continue

        # Sum across modules
        sum_term = 0
        for module in modules:
            # Nodes in this module
            module_mask = (module_labels == module)

            # Strength of connections from node i to nodes in this module
            kappa_is = np.nansum(connectivity_matrix[i, module_mask])

            # Add to sum
            sum_term += (kappa_is / k_i[i]) ** 2

        participation_coef[i] = 1 - sum_term

    return participation_coef

def classify_gateways_broadcasters(
    synergy_pc,
    redundancy_pc,
    workspace_mask
):
    """
    Classify workspace regions into gateways vs broadcasters.

    Step 2 of Luppi et al. (2024) Methods — "Subdivision of workspace nodes
    into gateways and broadcasters". Three reviewer-checkable properties of
    this implementation:
      (a) Uses **participation coefficient** (not node strength) — PC is
          computed in `compute_participation_coefficient` and passed in.
      (b) Uses the **8-module partition** (7 Yeo + 1 subcortical) via
          `rsn_labels` from `atlases/roi_to_network_mapping.csv` — the PC
          denominator iterates over all 8 unique module IDs.
      (c) Ranks are computed on the **within-workspace subset only**
          (`synergy_pc[valid_mask]`), NOT brain-wide. Non-workspace ROIs are
          excluded by construction and cannot be classified.
    The split is a pure **sign-of-rank-difference** test — no percentile
    threshold, no absolute cutoff. Gateway = positive sign, broadcaster =
    negative sign, matching Luppi exactly.

    Parameters
    ----------
    synergy_pc : array (454,)
        Participation coefficient based on synergy
    redundancy_pc : array (454,)
        Participation coefficient based on redundancy
    workspace_mask : array (454,) of bool
        True for workspace regions

    Returns
    -------
    gateway_mask : array (454,) of bool
    broadcaster_mask : array (454,) of bool
    pc_gradient : array (454,)
        Synergy PC rank - Redundancy PC rank (for workspace regions only)
    """
    # Only classify workspace regions, and only those with finite PC on both
    # measures. A workspace ROI should always have finite PC (workspace membership
    # requires finite node strength), but this guard protects against edge cases
    # where a ROI is zero-variance in every subject for one measure.
    valid_mask = workspace_mask & np.isfinite(synergy_pc) & np.isfinite(redundancy_pc)
    valid_indices = np.where(valid_mask)[0]

    # Rank participation coefficients (within valid workspace subset only).
    # scipy rankdata leaves NaN ranks as NaN; here we've already filtered NaN out.
    synergy_pc_valid = synergy_pc[valid_mask]
    redundancy_pc_valid = redundancy_pc[valid_mask]

    synergy_pc_ranks = scipy_stats.rankdata(synergy_pc_valid)
    redundancy_pc_ranks = scipy_stats.rankdata(redundancy_pc_valid)

    # Gradient: synergy PC rank - redundancy PC rank
    pc_gradient_valid = synergy_pc_ranks - redundancy_pc_ranks

    # Full gradient array (NaN for non-workspace and for excluded workspace ROIs)
    pc_gradient = np.full(N_ROIS, np.nan)
    pc_gradient[valid_mask] = pc_gradient_valid

    # Classify
    # Gateway: positive gradient (synergy rank > redundancy rank)
    # Broadcaster: negative gradient (redundancy rank > synergy rank)
    gateway_mask = np.zeros(N_ROIS, dtype=bool)
    broadcaster_mask = np.zeros(N_ROIS, dtype=bool)

    gateway_mask[valid_indices[pc_gradient_valid > 0]] = True
    broadcaster_mask[valid_indices[pc_gradient_valid < 0]] = True

    return gateway_mask, broadcaster_mask, pc_gradient

