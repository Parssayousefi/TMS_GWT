#!/usr/bin/env python3
"""
Gateway and Broadcaster Identification
=======================================

This script replicates the gateway/broadcaster analysis from Luppi et al. (2024):
1. Compute participation coefficient for synergy and redundancy networks
2. Identify workspace gateways (high synergy participation)
3. Identify workspace broadcasters (high redundancy participation)

**Dataset-agnostic**: Works with any configured dataset
**Supports multiple datasets**: Can process several datasets in one run
**Overwrite control**: Use --overwrite to recompute existing results

Based on Methods: "Subdivision of workspace nodes into gateways and broadcasters"

Key formula (from paper):
P_i = 1 - sum_s=1^M (κ_is / k_i)^2

where:
- κ_is = strength of connections between node i and nodes in module s
- k_i = total strength of node i
- M = number of modules (RSNs)

Usage:
------
# Single dataset
python scripts/analysis/06_identify_gateways_broadcasters.py --dataset london_lsd

# Multiple datasets
python scripts/analysis/06_identify_gateways_broadcasters.py --dataset london_lsd berlin_ketamine basel_mmm

# Force recomputation
python scripts/analysis/06_identify_gateways_broadcasters.py --dataset london_lsd --overwrite

# Pooled analysis (requires running script 05 with --compare first)
python scripts/analysis/06_identify_gateways_broadcasters.py --dataset london_lsd berlin_ketamine --pooled
"""

