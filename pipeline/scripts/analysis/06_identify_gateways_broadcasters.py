def process_pooled(dataset_names, project_dir=None, overwrite=False):
    """
    Process pooled data from multiple datasets.

    Requires script 05 to have been run with --compare flag first,
    which saves pooled group-average matrices.

    Parameters
    ----------
    dataset_names : list of str
        Dataset names that were pooled
    project_dir : Path, optional
        Project directory
    overwrite : bool
        If True, recompute even if outputs exist

    Returns
    -------
    dict or None
        Results dictionary, or None if failed
    """
    # Load first dataset handler to get project dir
    handler = load_dataset_handler(dataset_names[0], project_dir=project_dir)
    base_results_dir = handler.project_dir / 'results' / 'group_analysis'

    # Pooled results are in baseline_workspace_comparison/
    pooled_dir = base_results_dir / 'baseline_workspace_comparison'
    analysis_dir = pooled_dir  # Save outputs in same directory

    prefix = 'pooled'

    # Check if outputs already exist
    if not overwrite and check_outputs_exist(analysis_dir, prefix):
        print("\n" + "="*70)
        print("SKIPPING POOLED: outputs already exist")
        print("="*70)
        print(f"  Output directory: {analysis_dir}")
        print(f"  Use --overwrite to recompute")

        # Load and return existing results
        try:
            gateway_mask = np.load(analysis_dir / f'{prefix}_gateway_mask.npy')
            broadcaster_mask = np.load(analysis_dir / f'{prefix}_broadcaster_mask.npy')
            workspace_mask = np.load(analysis_dir / f'{prefix}_workspace_mask.npy')
            return {
                'dataset': 'pooled',
                'datasets_included': dataset_names,
                'control_task': 'pooled_placebo',
                'n_workspace': int(workspace_mask.sum()),
                'n_gateways': int(gateway_mask.sum()),
                'n_broadcasters': int(broadcaster_mask.sum()),
                'skipped': True
            }
        except:
            return None

    # Check that pooled files exist from script 05
    required_pooled_files = [
        'pooled_group_avg_synergy.npy',
        'pooled_group_avg_redundancy.npy',
        'pooled_workspace_mask.npy',
    ]
    missing = [f for f in required_pooled_files if not (pooled_dir / f).exists()]
    if missing:
        print("\n" + "="*70)
        print("ERROR: Pooled data not found")
        print("="*70)
        print(f"Missing files in {pooled_dir}:")
        for f in missing:
            print(f"  - {f}")
        print(f"\nPlease run script 05 with --compare first:")
        print(f"  python scripts/analysis/05_group_average_workspace.py --dataset {' '.join(dataset_names)} --compare")
        return None

    md_output = []

    def print_and_log(msg):
        print(msg)
        md_output.append(msg)

    print_and_log("="*70)
    print_and_log("GATEWAY AND BROADCASTER IDENTIFICATION (POOLED)")
    print_and_log("="*70)
    print_and_log(f"\nDatasets pooled: {', '.join(dataset_names)}")
    print_and_log("Replicating Luppi et al. (2024) methodology on pooled data")

    # -------------------------------------------------------------------------
    # Step 1: Load pooled data from script 05
    # -------------------------------------------------------------------------
    print_and_log("\n" + "="*70)
    print_and_log("STEP 1: Loading pooled group-average data from script 05")
    print_and_log("="*70)

    group_synergy = np.load(pooled_dir / 'pooled_group_avg_synergy.npy')
    group_redundancy = np.load(pooled_dir / 'pooled_group_avg_redundancy.npy')
    workspace_mask = np.load(pooled_dir / 'pooled_workspace_mask.npy')

    print_and_log(f"[OK] Loaded pooled group-average matrices: {group_synergy.shape}")
    print_and_log(f"[OK] Pooled workspace regions: {workspace_mask.sum()} / {N_ROIS}")

    # -------------------------------------------------------------------------
    # Step 2: Get RSN labels
    # -------------------------------------------------------------------------
    print_and_log("\n" + "="*70)
    print_and_log("STEP 2: Loading RSN module assignments")
    print_and_log("="*70)

    rsn_labels = get_rsn_labels(handler.project_dir)
    rsn_names = ['Visual', 'Somatomotor', 'DorsAttn', 'SalVentAttn', 'Limbic', 'Cont', 'Default', 'Subcortical']

    print_and_log("RSN assignments:")
    for i, name in enumerate(rsn_names):
        n_rois = (rsn_labels == i).sum()
        print_and_log(f"  {i}: {name:15s} - {n_rois} ROIs")

    # Save RSN labels
    np.save(analysis_dir / f'{prefix}_rsn_labels.npy', rsn_labels)

    # -------------------------------------------------------------------------
    # Step 3: Compute participation coefficients
    # -------------------------------------------------------------------------
    print_and_log("\n" + "="*70)
    print_and_log("STEP 3: Computing participation coefficients")
    print_and_log("="*70)

    print_and_log("Computing synergy participation coefficient...")
    synergy_pc = compute_participation_coefficient(group_synergy, rsn_labels)
    print_and_log(f"  Mean: {np.nanmean(synergy_pc):.4f}, Std: {np.nanstd(synergy_pc):.4f}, "
                  f"NaN: {int(np.isnan(synergy_pc).sum())}")
    print_and_log(f"  Range: [{np.nanmin(synergy_pc):.4f}, {np.nanmax(synergy_pc):.4f}]")

    print_and_log("\nComputing redundancy participation coefficient...")
    redundancy_pc = compute_participation_coefficient(group_redundancy, rsn_labels)
    print_and_log(f"  Mean: {np.nanmean(redundancy_pc):.4f}, Std: {np.nanstd(redundancy_pc):.4f}, "
                  f"NaN: {int(np.isnan(redundancy_pc).sum())}")
    print_and_log(f"  Range: [{np.nanmin(redundancy_pc):.4f}, {np.nanmax(redundancy_pc):.4f}]")

    np.save(analysis_dir / f'{prefix}_synergy_participation_coef.npy', synergy_pc)
    np.save(analysis_dir / f'{prefix}_redundancy_participation_coef.npy', redundancy_pc)

    # -------------------------------------------------------------------------
    # Step 4: Classify gateways and broadcasters
    # -------------------------------------------------------------------------
    print_and_log("\n" + "="*70)
    print_and_log("STEP 4: Classifying gateways and broadcasters")
    print_and_log("="*70)

    gateway_mask, broadcaster_mask, pc_gradient = classify_gateways_broadcasters(
        synergy_pc, redundancy_pc, workspace_mask
    )

    n_gateways = gateway_mask.sum()
    n_broadcasters = broadcaster_mask.sum()

    print_and_log(f"\nPooled workspace classification:")
    print_and_log(f"  Total workspace regions: {workspace_mask.sum()}")
    print_and_log(f"  Gateways: {n_gateways} (synergy PC rank > redundancy PC rank)")
    print_and_log(f"  Broadcasters: {n_broadcasters} (redundancy PC rank > synergy PC rank)")

    # Analyze RSN distribution
    print_and_log(f"\nGateway distribution by RSN:")
    for i, name in enumerate(rsn_names):
        n_gateways_in_rsn = np.sum(gateway_mask & (rsn_labels == i))
        n_total_in_rsn = np.sum(rsn_labels == i)
        pct = 100 * n_gateways_in_rsn / n_total_in_rsn if n_total_in_rsn > 0 else 0
        print_and_log(f"  {name:15s}: {n_gateways_in_rsn:3d} / {n_total_in_rsn:3d} ({pct:5.1f}%)")

    print_and_log(f"\nBroadcaster distribution by RSN:")
    for i, name in enumerate(rsn_names):
        n_broadcasters_in_rsn = np.sum(broadcaster_mask & (rsn_labels == i))
        n_total_in_rsn = np.sum(rsn_labels == i)
        pct = 100 * n_broadcasters_in_rsn / n_total_in_rsn if n_total_in_rsn > 0 else 0
        print_and_log(f"  {name:15s}: {n_broadcasters_in_rsn:3d} / {n_total_in_rsn:3d} ({pct:5.1f}%)")

    # -------------------------------------------------------------------------
    # Step 5: Save results
    # -------------------------------------------------------------------------
    print_and_log("\n" + "="*70)
    print_and_log("STEP 5: Saving pooled results")
    print_and_log("="*70)

    np.save(analysis_dir / f'{prefix}_gateway_mask.npy', gateway_mask)
    np.save(analysis_dir / f'{prefix}_broadcaster_mask.npy', broadcaster_mask)
    np.save(analysis_dir / f'{prefix}_pc_gradient.npy', pc_gradient)
    print_and_log("[OK] Saved gateway/broadcaster masks")

    # Summary DataFrame - ROI uses 1-454 to match atlas convention (see CLAUDE.md)
    summary_df = pd.DataFrame({
        'ROI': np.arange(1, N_ROIS + 1),
        'RSN': rsn_labels,
        'RSN_name': [rsn_names[label] for label in rsn_labels],
        'workspace': workspace_mask,
        'synergy_pc': synergy_pc,
        'redundancy_pc': redundancy_pc,
        'pc_gradient': pc_gradient,
        'gateway': gateway_mask,
        'broadcaster': broadcaster_mask
    })
    summary_df.to_csv(analysis_dir / f'{prefix}_gateway_broadcaster_summary.csv', index=False)
    print_and_log("[OK] Saved summary CSV")

    # Metadata
    metadata = {
        'analysis_type': 'pooled',
        'datasets_included': dataset_names,
        'n_rois': N_ROIS,
        'n_workspace': int(workspace_mask.sum()),
        'n_gateways': int(n_gateways),
        'n_broadcasters': int(n_broadcasters),
        'n_rsns': len(rsn_names),
        'rsn_names': rsn_names,
        'analysis_date': pd.Timestamp.now().isoformat(),
        'output_directory': str(analysis_dir),
        'file_prefix': prefix,
        'notes': 'Gateway/broadcaster classification on pooled placebo data across multiple datasets'
    }

    with open(analysis_dir / f'{prefix}_gateway_broadcaster_metadata.yaml', 'w') as f:
        yaml.dump(metadata, f, default_flow_style=False)
    print_and_log("[OK] Saved metadata")

    print_and_log("\n" + "="*70)
    print_and_log("POOLED GATEWAY/BROADCASTER ANALYSIS COMPLETE")
    print_and_log("="*70)
    print_and_log(f"\nResults saved to: {analysis_dir}")
    print_and_log(f"File prefix: {prefix}_*")
    print_and_log(f"\nKey findings:")
    print_and_log(f"  - Paper prediction: Gateways = DMN, Broadcasters = FPN")

    # Save markdown
    md_file = analysis_dir / f'{prefix}_gateway_broadcaster_results.md'
    with open(md_file, 'w') as f:
        f.write('\n'.join(md_output))
    print(f"\n[OK] Markdown output saved to: {md_file}")

    return {
        'dataset': 'pooled',
        'datasets_included': dataset_names,
        'control_task': 'pooled_placebo',
        'n_workspace': int(workspace_mask.sum()),
        'n_gateways': int(n_gateways),
        'n_broadcasters': int(n_broadcasters),
        'output_dir': str(analysis_dir),
        'skipped': False
    }


def process_dataset(dataset_name, project_dir=None, overwrite=False, task=None, control_task=None, workspace_dataset='hcp'):
    """
    Process a single dataset: compute gateway/broadcaster classification.

    IMPORTANT: The workspace should be defined using the CONTROL condition to avoid
    circular reasoning. When analyzing drug conditions, use --control_task to specify
    which condition defines the workspace, and --task for the connectivity matrices.

    Parameters
    ----------
    dataset_name : str
        Dataset name (e.g., 'london_lsd', 'basel_mmm')
    project_dir : Path, optional
        Project directory
    overwrite : bool
        If True, recompute even if outputs exist
    task : str, optional
        Task/condition for connectivity matrices. If None, uses control task.
    control_task : str, optional
        Task/condition that defines the workspace mask. If None, uses same as task.
        For drug analyses, this should be the placebo/control condition.
    workspace_dataset : str, optional
        Dataset that defines the canonical workspace. Defaults to 'hcp' per Luppi et al.:
        the HCP workspace (100 healthy controls) is projected onto all drug datasets to
        avoid circular reasoning. Pass the same value as `dataset_name` only for rare
        sensitivity checks. Matches the CLI default at argparse `--workspace_dataset hcp`.

    Returns
    -------
    dict or None
        Results dictionary, or None if skipped/failed
    """
    # Load dataset handler
    handler = load_dataset_handler(dataset_name, project_dir=project_dir)

    # Use provided task or default to control task
    if task is None:
        task = get_control_task_name(dataset_name)
    target_task = task  # Task for connectivity matrices

    # Use provided control_task for workspace definition, or same as target_task
    if control_task is None:
        workspace_task = target_task
    else:
        workspace_task = control_task

    # Setup paths
    base_results_dir = handler.project_dir / 'results' / 'group_analysis'

    # Workspace source: use workspace_dataset if specified, otherwise own dataset
    if workspace_dataset and workspace_dataset != dataset_name:
        ws_handler = load_dataset_handler(workspace_dataset, project_dir=project_dir)
        ws_task = get_control_task_name(workspace_dataset)
        workspace_source_dir = base_results_dir / workspace_dataset / ws_task
        workspace_prefix = f"{workspace_dataset}_{ws_task}"
        workspace_source_dataset = workspace_dataset
        workspace_source_task = ws_task
    else:
        workspace_source_dir = base_results_dir / dataset_name / workspace_task
        workspace_prefix = f"{dataset_name}_{workspace_task}"
        workspace_source_dataset = dataset_name
        workspace_source_task = workspace_task

    # Connectivity matrices come from target_task directory
    connectivity_dir = base_results_dir / dataset_name / target_task
    connectivity_prefix = f"{dataset_name}_{target_task}"

    # Output goes to target_task directory
    analysis_dir = connectivity_dir
    analysis_dir.mkdir(exist_ok=True, parents=True)

    # File prefix for outputs
    prefix = f"{dataset_name}_{target_task}"

    # Check if outputs already exist
    if not overwrite and check_outputs_exist(analysis_dir, prefix):
        print(f"\n{'='*70}")
        print(f"SKIPPING {dataset_name} ({target_task}): outputs already exist")
        print(f"{'='*70}")
        print(f"  Output directory: {analysis_dir}")
        print(f"  Use --overwrite to recompute")

        # Load and return existing results for summary
        try:
            gateway_mask = np.load(analysis_dir / f'{prefix}_gateway_mask.npy')
            broadcaster_mask = np.load(analysis_dir / f'{prefix}_broadcaster_mask.npy')
            workspace_mask = np.load(workspace_source_dir / f'{workspace_prefix}_workspace_mask.npy')
            return {
                'dataset': dataset_name,
                'control_task': target_task,  # Note: kept key name for compatibility
                'workspace_task': workspace_source_task,
                'workspace_source_dataset': workspace_source_dataset,
                'n_workspace': int(workspace_mask.sum()),
                'n_gateways': int(gateway_mask.sum()),
                'n_broadcasters': int(broadcaster_mask.sum()),
                'skipped': True
            }
        except:
            return None

    # Create markdown output file
    md_output = []

    def print_and_log(msg):
        """Print to console and log to markdown"""
        print(msg)
        md_output.append(msg)

    print_and_log("="*70)
    print_and_log("GATEWAY AND BROADCASTER IDENTIFICATION")
    print_and_log("="*70)
    print_and_log(f"\nDataset: {handler.config['name']}")
    print_and_log(f"Connectivity task: {target_task}")
    print_and_log(f"Workspace source dataset: {workspace_source_dataset}")
    print_and_log(f"Workspace source task: {workspace_source_task}")
    if workspace_source_dataset != dataset_name:
        print_and_log(f"  (Using {workspace_source_dataset} workspace per Luppi et al.)")
    elif workspace_source_task != target_task:
        print_and_log(f"  (Using control-defined workspace to avoid circular reasoning)")
    print_and_log(f"Replicating Luppi et al. (2024) methodology")
    print_and_log(f"Using participation coefficient to classify workspace regions")

    # -------------------------------------------------------------------------
    # Step 1: Load data from script 05
    # -------------------------------------------------------------------------
    print_and_log("\n" + "="*70)
    print_and_log("STEP 1: Loading data from script 05")
    print_and_log("="*70)

    # Load workspace mask from control condition
    try:
        workspace_mask = np.load(workspace_source_dir / f'{workspace_prefix}_workspace_mask.npy')
        print_and_log(f"[OK] Loaded workspace mask from {workspace_task}: {workspace_mask.sum()} regions")
    except FileNotFoundError as e:
        print_and_log(f"\nERROR: Could not find workspace mask for {dataset_name} ({workspace_task})")
        print_and_log(f"  {e}")
        print_and_log(f"\nPlease run 05_group_average_workspace.py for control condition first:")
        print_and_log(f"  python scripts/analysis/05_group_average_workspace.py --dataset {dataset_name}")
        return None

    # Load connectivity matrices from target task
    try:
        group_synergy = np.load(connectivity_dir / f'{connectivity_prefix}_group_avg_synergy.npy')
        group_redundancy = np.load(connectivity_dir / f'{connectivity_prefix}_group_avg_redundancy.npy')
        print_and_log(f"[OK] Loaded connectivity matrices from {target_task}: {group_synergy.shape}")
    except FileNotFoundError as e:
        print_and_log(f"\nERROR: Could not find connectivity results for {dataset_name} ({target_task})")
        print_and_log(f"  {e}")
        print_and_log(f"\nPlease run 05_group_average_workspace.py for this task first:")
        print_and_log(f"  python scripts/analysis/05_group_average_workspace.py --dataset {dataset_name} --task {target_task}")
        return None

    print_and_log(f"[OK] Workspace regions: {workspace_mask.sum()} / {N_ROIS}")

    # -------------------------------------------------------------------------
    # Step 2: Get RSN labels
    # -------------------------------------------------------------------------
    print_and_log("\n" + "="*70)
    print_and_log("STEP 2: Loading RSN module assignments")
    print_and_log("="*70)

    rsn_labels = get_rsn_labels(handler.project_dir)
    rsn_names = ['Visual', 'Somatomotor', 'DorsAttn', 'SalVentAttn', 'Limbic', 'Cont', 'Default', 'Subcortical']

    print_and_log(f"RSN assignments:")
    for i, name in enumerate(rsn_names):
        n_rois = (rsn_labels == i).sum()
        print_and_log(f"  {i}: {name:15s} - {n_rois} ROIs")

    # Save RSN labels
    np.save(analysis_dir / f'{prefix}_rsn_labels.npy', rsn_labels)

    # -------------------------------------------------------------------------
    # Step 3: Compute participation coefficients
    # -------------------------------------------------------------------------
    print_and_log("\n" + "="*70)
    print_and_log("STEP 3: Computing participation coefficients")
    print_and_log("="*70)

    print_and_log("Computing synergy participation coefficient...")
    synergy_pc = compute_participation_coefficient(group_synergy, rsn_labels)
    print_and_log(f"  Mean: {np.nanmean(synergy_pc):.4f}, Std: {np.nanstd(synergy_pc):.4f}, "
                  f"NaN: {int(np.isnan(synergy_pc).sum())}")
    print_and_log(f"  Range: [{np.nanmin(synergy_pc):.4f}, {np.nanmax(synergy_pc):.4f}]")

    print_and_log("\nComputing redundancy participation coefficient...")
    redundancy_pc = compute_participation_coefficient(group_redundancy, rsn_labels)
    print_and_log(f"  Mean: {np.nanmean(redundancy_pc):.4f}, Std: {np.nanstd(redundancy_pc):.4f}, "
                  f"NaN: {int(np.isnan(redundancy_pc).sum())}")
    print_and_log(f"  Range: [{np.nanmin(redundancy_pc):.4f}, {np.nanmax(redundancy_pc):.4f}]")

    # Save participation coefficients
    np.save(analysis_dir / f'{prefix}_synergy_participation_coef.npy', synergy_pc)
    np.save(analysis_dir / f'{prefix}_redundancy_participation_coef.npy', redundancy_pc)

    # -------------------------------------------------------------------------
    # Step 4: Classify gateways and broadcasters
    # -------------------------------------------------------------------------
    print_and_log("\n" + "="*70)
    print_and_log("STEP 4: Classifying gateways and broadcasters")
    print_and_log("="*70)

    gateway_mask, broadcaster_mask, pc_gradient = classify_gateways_broadcasters(
        synergy_pc, redundancy_pc, workspace_mask
    )

    n_gateways = gateway_mask.sum()
    n_broadcasters = broadcaster_mask.sum()

    print_and_log(f"\nWorkspace classification:")
    print_and_log(f"  Total workspace regions: {workspace_mask.sum()}")
    print_and_log(f"  Gateways: {n_gateways} (synergy PC rank > redundancy PC rank)")
    print_and_log(f"  Broadcasters: {n_broadcasters} (redundancy PC rank > synergy PC rank)")

    # Analyze RSN distribution of gateways/broadcasters
    print_and_log(f"\nGateway distribution by RSN:")
    for i, name in enumerate(rsn_names):
        n_gateways_in_rsn = np.sum(gateway_mask & (rsn_labels == i))
        n_total_in_rsn = np.sum(rsn_labels == i)
        pct = 100 * n_gateways_in_rsn / n_total_in_rsn if n_total_in_rsn > 0 else 0
        print_and_log(f"  {name:15s}: {n_gateways_in_rsn:3d} / {n_total_in_rsn:3d} ({pct:5.1f}%)")

    print_and_log(f"\nBroadcaster distribution by RSN:")
    for i, name in enumerate(rsn_names):
        n_broadcasters_in_rsn = np.sum(broadcaster_mask & (rsn_labels == i))
        n_total_in_rsn = np.sum(rsn_labels == i)
        pct = 100 * n_broadcasters_in_rsn / n_total_in_rsn if n_total_in_rsn > 0 else 0
        print_and_log(f"  {name:15s}: {n_broadcasters_in_rsn:3d} / {n_total_in_rsn:3d} ({pct:5.1f}%)")

    # -------------------------------------------------------------------------
    # Step 5: Save results
    # -------------------------------------------------------------------------
    print_and_log("\n" + "="*70)
    print_and_log("STEP 5: Saving results")
    print_and_log("="*70)

    np.save(analysis_dir / f'{prefix}_gateway_mask.npy', gateway_mask)
    np.save(analysis_dir / f'{prefix}_broadcaster_mask.npy', broadcaster_mask)
    np.save(analysis_dir / f'{prefix}_pc_gradient.npy', pc_gradient)
    print_and_log("[OK] Saved gateway/broadcaster masks")

    # Create summary DataFrame - ROI uses 1-454 to match atlas convention (see CLAUDE.md)
    summary_df = pd.DataFrame({
        'ROI': np.arange(1, N_ROIS + 1),
        'RSN': rsn_labels,
        'RSN_name': [rsn_names[label] for label in rsn_labels],
        'workspace': workspace_mask,
        'synergy_pc': synergy_pc,
        'redundancy_pc': redundancy_pc,
        'pc_gradient': pc_gradient,
        'gateway': gateway_mask,
        'broadcaster': broadcaster_mask
    })
    summary_df.to_csv(analysis_dir / f'{prefix}_gateway_broadcaster_summary.csv', index=False)
    print_and_log("[OK] Saved summary CSV")

    # Metadata
    metadata = {
        'dataset': dataset_name,
        'dataset_name': handler.config['name'],
        'connectivity_task': target_task,
        'workspace_task': workspace_source_task,
        'workspace_source_dataset': workspace_source_dataset,
        'workspace_source_task': workspace_source_task,
        'workspace_source_path': str(workspace_source_dir),
        'workspace_from_control': workspace_source_task != target_task,
        'workspace_from_external_dataset': workspace_source_dataset != dataset_name,
        'n_rois': N_ROIS,
        'n_workspace': int(workspace_mask.sum()),
        'n_gateways': int(n_gateways),
        'n_broadcasters': int(n_broadcasters),
        'n_rsns': len(rsn_names),
        'rsn_names': rsn_names,
        'analysis_date': pd.Timestamp.now().isoformat(),
        'output_directory': str(analysis_dir),
        'file_prefix': prefix,
        'notes': 'Gateway/broadcaster classification based on participation coefficient (Luppi et al. 2024). '
                 f'Workspace defined by {workspace_source_dataset}/{workspace_source_task}, connectivity from {dataset_name}/{target_task}.'
    }

    with open(analysis_dir / f'{prefix}_gateway_broadcaster_metadata.yaml', 'w') as f:
        yaml.dump(metadata, f, default_flow_style=False)
    print_and_log("[OK] Saved metadata")

    print_and_log("\n" + "="*70)
    print_and_log("GATEWAY/BROADCASTER ANALYSIS COMPLETE")
    print_and_log("="*70)
    print_and_log(f"\nResults saved to: {analysis_dir}")
    print_and_log(f"File prefix: {prefix}_*")
    print_and_log(f"\nKey findings:")
    print_and_log(f"  - Paper prediction: Gateways = DMN, Broadcasters = FPN")
    print_and_log(f"  - Check '{prefix}_gateway_broadcaster_summary.csv' to verify")

    # Save markdown output
    md_file = analysis_dir / f'{prefix}_gateway_broadcaster_results.md'
    with open(md_file, 'w') as f:
        f.write('\n'.join(md_output))
    print(f"\n[OK] Markdown output saved to: {md_file}")

    return {
        'dataset': dataset_name,
        'control_task': target_task,  # Note: kept key name for compatibility
        'workspace_task': workspace_source_task,
        'workspace_source_dataset': workspace_source_dataset,
        'n_workspace': int(workspace_mask.sum()),
        'n_gateways': int(n_gateways),
        'n_broadcasters': int(n_broadcasters),
        'output_dir': str(analysis_dir),
        'skipped': False
    }


def main():
    """Main analysis pipeline"""
    parser = argparse.ArgumentParser(
        description='Gateway/broadcaster identification (Luppi et al. 2024)',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Single dataset (uses HCP workspace by default)
  python 06_identify_gateways_broadcasters.py --dataset london_lsd

  # Drug condition analysis (HCP workspace + control task connectivity)
  python 06_identify_gateways_broadcasters.py --dataset london_lsd --task LSD --control_task PCB

  # Use dataset-specific workspace instead of HCP
  python 06_identify_gateways_broadcasters.py --dataset london_lsd --workspace_dataset london_lsd

  # Multiple datasets
  python 06_identify_gateways_broadcasters.py --dataset london_lsd berlin_ketamine

  # Force recomputation
  python 06_identify_gateways_broadcasters.py --dataset london_lsd --overwrite

  # Pooled analysis (requires script 05 --compare first)
  python 06_identify_gateways_broadcasters.py --dataset london_lsd berlin_ketamine --pooled
        """
    )
    parser.add_argument('--dataset', required=True, nargs='+',
                       help='One or more dataset names (e.g., london_lsd basel_mmm)')
    parser.add_argument('--pooled', action='store_true',
                       help='Run on pooled data from script 05 --compare (requires 2+ datasets)')
    parser.add_argument('--overwrite', action='store_true',
                       help='Overwrite existing results (default: skip if outputs exist)')
    parser.add_argument('--project_dir', help='Project directory (optional)')
    parser.add_argument('--task', help='Task/condition for connectivity matrices (default: control task). E.g., LSD, ketamine, MDMA')
    parser.add_argument('--control_task', help='Task/condition that defines the workspace (default: same as --task). '
                       'For drug analyses, use the placebo/control condition to avoid circular reasoning.')
    parser.add_argument('--workspace_dataset', default='hcp',
                       help='Dataset that defines the canonical workspace (default: hcp). '
                       'The HCP workspace is the canonical reference per Luppi et al. '
                       'Set to same as --dataset to use dataset-specific workspace.')

    args = parser.parse_args()

    print("="*70)
    print("GATEWAY/BROADCASTER IDENTIFICATION PIPELINE")
    print("="*70)
    print(f"Datasets: {', '.join(args.dataset)}")
    print(f"Connectivity task: {args.task if args.task else '(control)'}")
    print(f"Workspace task: {args.control_task if args.control_task else '(same as connectivity)'}")
    print(f"Workspace dataset: {args.workspace_dataset}")
    print(f"Pooled mode: {args.pooled}")
    print(f"Overwrite: {args.overwrite}")
    print()

    all_results = []

    # --- POOLED MODE ---
    if args.pooled:
        if len(args.dataset) < 2:
            print("ERROR: --pooled requires at least 2 datasets")
            return

        print(f"\n{'#'*70}")
        print(f"# Processing: POOLED ({', '.join(args.dataset)})")
        print(f"{'#'*70}")

        try:
            result = process_pooled(
                args.dataset,
                project_dir=args.project_dir,
                overwrite=args.overwrite
            )
            if result:
                all_results.append(result)
        except Exception as e:
            print(f"\nERROR processing pooled data: {e}")
            import traceback
            traceback.print_exc()

    # --- PER-DATASET MODE ---
    # Process each dataset individually (in addition to pooled if both requested)
    for dataset_name in args.dataset:
        task_str = f" (connectivity={args.task})" if args.task else ""
        ctrl_str = f" (workspace={args.control_task})" if args.control_task else ""
        print(f"\n{'#'*70}")
        print(f"# Processing: {dataset_name}{task_str}{ctrl_str}")
        print(f"{'#'*70}")

        try:
            result = process_dataset(
                dataset_name,
                project_dir=args.project_dir,
                overwrite=args.overwrite,
                task=args.task,
                control_task=args.control_task,
                workspace_dataset=args.workspace_dataset
            )
            if result:
                all_results.append(result)
        except Exception as e:
            print(f"\nERROR processing {dataset_name}: {e}")
            import traceback
            traceback.print_exc()

    # Print summary
    print("\n" + "="*70)
    print("SUMMARY")
    print("="*70)

    if not all_results:
        print("No datasets processed successfully.")
        return

    print(f"\n{'Dataset':<20} {'Control':<10} {'Workspace':<12} {'Gateways':<10} {'Broadcasters':<12} {'Status'}")
    print("-"*76)
    for r in all_results:
        status = "skipped" if r.get('skipped', False) else "computed"
        print(f"{r['dataset']:<20} {r['control_task']:<10} {r['n_workspace']:<12} {r['n_gateways']:<10} {r['n_broadcasters']:<12} {status}")

    print(f"\nNext steps:")
    for r in all_results:
        print(f"  python scripts/analysis/06b_compare_conditions_gateways.py --dataset {r['dataset']} --drug_task <DRUG>")

if __name__ == '__main__':
    main()
