"""Export the authoritative per-scan analysis-inclusion list for a dataset.

WHY THIS EXISTS
    The Python analyses gate scans through
    analysis_loader.discover_processed_scans(), which honours
    `qc.honor_exclusions_in_analysis` in the dataset config and therefore drops
    ART-excluded scans (cambridge_propofol: 14/14/16 -> 11/12/16 paired).
    The R dashboard's discover_phiid() globs results/phiid_matrices directly and
    applies NO QC gate, so it analysed 14/14/16. Same cohort, two sample sizes,
    same manuscript.

    Rather than reimplement the gate in R (two implementations = two chances to
    drift), this script exports the Python gate's own verdict to a CSV that both
    languages read. Whatever the config says, both agree by construction.

OUTPUT
    results/qc/{dataset}/analysis_inclusion.csv
        dataset, subject, session, task, run, scan_id, included, reason
    One row per scan that has PhiID output on disk. `included` is TRUE/FALSE
    (title case, so R's readr parses it as logical, matching the convention
    already used by the workspace CSVs).

USAGE
    python scripts/qc/export_analysis_inclusion.py --dataset cambridge_propofol
    python scripts/qc/export_analysis_inclusion.py --all
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

PROJECT_DIR = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_DIR / "scripts" / "utils"))

from analysis_loader import discover_processed_scans  # noqa: E402
from dataset_handler import load_dataset_handler, list_active_datasets  # noqa: E402
from qc_loader import QCExclusions  # noqa: E402


def scan_id_for(handler, scan: dict) -> str:
    sub = scan["subject"]
    ses = scan.get("session")
    task = scan["task"]
    run = int(scan.get("run", 1) or 1)
    parts = [f"sub-{sub}"]
    if ses:
        parts.append(f"ses-{ses}")
    parts += [f"task-{task}", f"run-{run}"]
    return "_".join(parts)


def export(dataset: str) -> Path:
    handler = load_dataset_handler(dataset)
    qc_cfg = handler.config.get("qc", {}) or {}
    honor = bool(qc_cfg.get("honor_exclusions_in_analysis", False))

    # Gated view: exactly what the Python analyses see.
    gated = discover_processed_scans(dataset)
    gated_keys = {(s["subject"], s.get("session"), s["task"]) for s in gated}

    # Ungated view: every scan with PhiID output, so excluded rows are still
    # listed (with a reason) instead of silently vanishing.
    phiid_dir = PROJECT_DIR / "results" / "phiid_matrices"
    all_scans = []
    for scan in handler.discover_all_scans():
        sid = scan_id_for(handler, scan)
        if (phiid_dir / f"dataset-{dataset}_{sid}_synergy.npy").exists():
            all_scans.append(scan)

    qc = QCExclusions(dataset) if honor else None
    rows = []
    for scan in all_scans:
        key = (scan["subject"], scan.get("session"), scan["task"])
        included = key in gated_keys
        reason = ""
        if not included:
            reason = "QC EXCLUDE (motion and/or ART)" if honor else "not returned by gate"
        rows.append({
            "dataset": dataset,
            "subject": scan["subject"],
            "session": scan.get("session") or "",
            "task": scan["task"],
            "run": int(scan.get("run", 1) or 1),
            "scan_id": scan_id_for(handler, scan),
            "included": "True" if included else "False",
            "reason": reason,
        })

    df = pd.DataFrame(rows).sort_values(["task", "subject"]).reset_index(drop=True)
    out_dir = PROJECT_DIR / "results" / "qc" / dataset
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / "analysis_inclusion.csv"
    with open(out, "w", newline="", encoding="utf-8") as f:
        f.write(f"# Authoritative analysis-inclusion list for {dataset}\n")
        f.write(f"# honor_exclusions_in_analysis: {honor}\n")
        f.write("# Generated by scripts/qc/export_analysis_inclusion.py — the R dashboard\n")
        f.write("# and the Python analyses both filter on this file, so they cannot drift.\n")
        df.to_csv(f, index=False)

    n_in = (df.included == "True").sum()
    print(f"{dataset}: honor_exclusions={honor}  {n_in}/{len(df)} scans included")
    per_task = (df.assign(inc=df.included.eq("True"))
                  .groupby("task")["inc"].agg(["sum", "count"]))
    for task, r in per_task.iterrows():
        print(f"    {task:16s} {int(r['sum']):3d} / {int(r['count']):3d}")
    print(f"    -> {out}")
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--dataset")
    g.add_argument("--all", action="store_true")
    args = ap.parse_args()

    datasets = list_active_datasets() if args.all else [args.dataset]
    for ds in datasets:
        try:
            export(ds)
        except Exception as e:  # keep --all going
            print(f"{ds}: FAILED ({type(e).__name__}: {e})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
